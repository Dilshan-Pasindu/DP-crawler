import type {
  ErrorRecord,
  InteractionExecutionResult,
  InteractionObservation,
  SignalEvent,
} from "../model/index.js";

export interface ErrorAttributionResult {
  readonly attributable: boolean;
  readonly reason: string;
}

/**
 * Determines whether an observed error during an interaction window should be attributed
 * as an application failure. Crawler safety blocks, background noise, third-party errors,
 * expected errors, and uncontexted 400/401/403/404 responses are not auto-classified as FAIL.
 */
export function attributeError(error: ErrorRecord): ErrorAttributionResult {
  if (error.blockedByCrawler === true || error.source === "crawler") {
    return { attributable: false, reason: "Generated by crawler safety guard" };
  }
  if (error.expected === true) {
    return { attributable: false, reason: "Marked as expected application error" };
  }
  if (error.source === "third-party" || error.source === "background") {
    return { attributable: false, reason: `Non-target error source: ${error.source}` };
  }
  if (
    error.statusCode !== undefined &&
    (error.statusCode === 400 || error.statusCode === 401 || error.statusCode === 403 || error.statusCode === 404) &&
    error.source !== "application"
  ) {
    return { attributable: false, reason: `HTTP ${error.statusCode} requires explicit application attribution` };
  }
  if (error.source === "application" || (error.statusCode !== undefined && error.statusCode >= 500)) {
    return { attributable: true, reason: "Attributable application failure or HTTP 5xx" };
  }
  return { attributable: false, reason: "Insufficient attribution evidence" };
}

function isReactionSignal(signal: SignalEvent): boolean {
  return (
    signal.kind === "url-change" ||
    signal.kind === "navigation" ||
    signal.kind === "dom-mutation" ||
    signal.kind === "accessibility-event" ||
    signal.kind === "state-change" ||
    signal.kind === "dialog" ||
    signal.kind === "popup" ||
    signal.kind === "download" ||
    signal.kind === "notification" ||
    signal.kind === "visual-change"
  );
}

/**
 * Correlates signals from both inside and outside the clicked element's subtree
 * (e.g., portal toast notifications, navigation, dialogs, and attributed errors).
 */
export function correlateSignals(
  nodeKey: string,
  execution: InteractionExecutionResult,
): InteractionObservation {
  const attributedErrors: ErrorRecord[] = [];
  for (const sig of execution.signals) {
    if (sig.error !== undefined && attributeError(sig.error).attributable) {
      attributedErrors.push(sig.error);
    }
  }

  const reactionSignals = execution.signals.filter(isReactionSignal);
  const changeDetected = reactionSignals.length > 0;
  const changeCorrelated = reactionSignals.some(
    (s) => s.inClickedSubtree || s.targetKey === nodeKey || s.kind === "notification" || s.kind === "url-change" || s.kind === "navigation" || s.kind === "dialog" || s.kind === "popup" || s.kind === "download",
  );

  const attributionConfidence: "HIGH" | "MEDIUM" | "LOW" =
    attributedErrors.some((e) => e.source === "application") ||
    reactionSignals.some((s) => s.inClickedSubtree || s.targetKey === nodeKey)
      ? "HIGH"
      : changeCorrelated || attributedErrors.length > 0
        ? "MEDIUM"
        : "LOW";

  return {
    interactionAttempted: execution.attempted,
    interactionSucceeded: execution.succeeded,
    interactionDetected: execution.attempted && execution.succeeded,
    changeDetected,
    changeCorrelated,
    expectedBehaviourVerified: false,
    attributedErrors,
    attributionConfidence,
    signals: execution.signals,
    obscured: execution.obscured,
    unstable: execution.unstable,
    ...(execution.unsupportedReason !== undefined ? { reason: execution.unsupportedReason } : {}),
  };
}
